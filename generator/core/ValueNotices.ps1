.DESCRIPTION
    Part of Build-HardwareProfile.ps1, dot-sourced into its script scope (uses its constants and $script: state).
    A <ValueNotice> names a selection (ParameterRef, producer tokens allowed) and a <BoardTable> whose index is the value of
    the selection. Per board the table gives All (set in every env) and Any (set in at least one env); the block
    ValueNotice_<name> shows the "all" text (UIHint Error) while the selection holds a value set in every env of the selected
    board, the "any" text (UIHint Information) while it holds a value set only in some. Pure XML, no script.
