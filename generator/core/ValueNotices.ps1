# @brief Values of one board for a <ValueNotice>: All = indices set (non-zero) in every env, Any = indices set in some env only
function Get-ValueNoticeSets($Board, [string]$Table) {
  $all = @(); $any = @()
  $t = $null; if ($Board.Tables) { $t = $Board.Tables[$Table] }
  if ($t) {
    foreach ($ix in @($t.All.Keys | Sort-Object { [int]$_ })) { if ([int]$t.All[$ix] -ne 0) { $all += [int]$ix } }
    foreach ($ix in @($t.Any.Keys | Sort-Object { [int]$_ })) { if ([int]$t.Any[$ix] -ne 0 -and $all -notcontains [int]$ix) { $any += [int]$ix } }
  }
  return @{ All = $all; Any = $any }
}

# @brief Parts file of <ValueNotices>: per <ValueNotice> a block ValueNotice_<name> in place under the selection: a choose on
#        the hardware selection (module digits, valid in a template or part of another module), one when per group of boards
#        with the same values, inside a choose on the selection with the "all" and the "any" text; boards without a value and
#        "not selected" get no when (no notice). A notice without any board value gives an empty block.
function New-ValueNoticesXml($M, $Boards) {
  $refs = Get-ParamRefIds $M
  $sb = New-Object System.Text.StringBuilder
  [void]$sb.AppendLine('<?xml version="1.0" encoding="utf-8"?>')
  [void]$sb.AppendLine('<KNX xmlns="http://knx.org/xml/project/20" xmlns:op="http://github.com/OpenKNX/OpenKNXproducer">')
  [void]$sb.AppendLine("  <!-- Generated by OGM-HardwareConfig/generator/Build-HardwareProfile.ps1 (<ValueNotices>) - do not edit -->")
  [void]$sb.AppendLine("  <!-- include: block ValueNotice_<name> under the selection it names (same template or part, the ref keeps its tokens) -->")
  foreach ($n in $M.ValueNotices.Items) {
    $groups = New-Object System.Collections.Generic.List[object]
    foreach ($b in $Boards) {
      $s = Get-ValueNoticeSets $b $n.Table
      $sa = @($s.All); $sn = @($s.Any)
      if (-not $n.AllText) { $sa = @() }
      if (-not $n.AnyText) { $sn = @() }
      if ($sa.Count -eq 0 -and $sn.Count -eq 0) { continue }
      $key = ($sa -join " ") + "|" + ($sn -join " ")
      $g = @($groups | Where-Object { $_.Key -ceq $key }) | Select-Object -First 1
      if (-not $g) { $g = @{ Key = $key; All = $sa; Any = $sn; Boards = @() }; $groups.Add($g) }
      $g.Boards += $b
    }
    [void]$sb.AppendLine(("  <Block name=`"ValueNotice_{0}`">" -f $n.Name))
    if ($groups.Count -gt 0) {
      [void]$sb.AppendLine(("    <choose ParamRefId=`"{0}`">" -f $refs.Select))
      foreach ($g in $groups) {
        [void]$sb.AppendLine(("      <when test=`"{0}`">" -f (Get-IdList $g.Boards)))
        [void]$sb.AppendLine(("        <choose ParamRefId=`"{0}`">" -f $n.Ref))
        if ($g.All.Count -gt 0) { [void]$sb.AppendLine(("          <when test=`"{0}`"><ParameterSeparator Id=`"%AID%_PS-nnn`" Text=`"{1}`" UIHint=`"Error`" /></when>" -f ($g.All -join " "), (ConvertTo-XmlText $n.AllText))) }
        if ($g.Any.Count -gt 0) { [void]$sb.AppendLine(("          <when test=`"{0}`"><ParameterSeparator Id=`"%AID%_PS-nnn`" Text=`"{1}`" UIHint=`"Information`" /></when>" -f ($g.Any -join " "), (ConvertTo-XmlText $n.AnyText))) }
        [void]$sb.AppendLine("        </choose>")
        [void]$sb.AppendLine("      </when>")
      }
      [void]$sb.AppendLine("    </choose>")
    }
    [void]$sb.AppendLine("  </Block>")
  }
  [void]$sb.AppendLine('</KNX>')
  return $sb.ToString()
}
